#!/usr/bin/env node
/**
 * Fails when a shipped model is far larger than the pipeline can explain.
 *
 * Four monster GLBs were committed at 20.5 MB between them — frost_imp alone was
 * 7.81 MB — while the tool that shrinks them sat in this same directory. They
 * went in raw for a mundane reason: optimize-glb.cjs did require("playwright"),
 * this repo depends on playwright-core, so the require always threw, the script
 * printed "playwright/chromium unavailable" and EXITED 0. Anyone who ran it was
 * told it could not work, and the build got the raw files.
 *
 * Optimised, those four are 1.80 MB. The tool's own header records the same
 * result for the earlier set: 21.5 MB to 1.53 MB, no visible change, because a
 * character GLB is overwhelmingly texture and these actors render ~40 px tall.
 *
 * So the threshold below is not a style rule. Anything much above it means a
 * model skipped the pipeline, and the download budget is what pays for it — a
 * budget the whole plan is shaped around, on phones, on mobile data.
 *
 * Run: npm run verify:models
 */
const fs = require("fs");
const path = require("path");

// Generous: the largest legitimately optimised model here is hero_rigged at
// 0.70 MB. 1.5 MB leaves room for a genuinely denser character without letting
// an unprocessed multi-megabyte export through.
const MAX_BYTES = 1.5 * 1024 * 1024;

// The SOURCE archive. Everything here is under direct control and a model that
// skipped the pipeline is a hard failure.
const SOURCE_ROOT = "unity/Assets/Isoperia/Art/Models";

// The GENERATED mirror that actually ships. IsoperiaOwnedModelPreparation copies
// from the source into here, and only the Unity Editor can regenerate it — so an
// oversized file here is REPORTED but does not fail the build: it is not
// something a code-lane change can fix, and a permanently red gate is worse than
// no gate. It names the exact step that resolves it.
const MIRROR_ROOT = "unity/Assets/Isoperia/Resources/Art/OwnedModels";

let failures = 0;
let checked = 0;
let lfs = 0;
let total = 0;

let stale = 0;

for (const root of [SOURCE_ROOT, MIRROR_ROOT]) {
  if (!fs.existsSync(root)) continue;
  const isMirror = root === MIRROR_ROOT;

  for (const name of fs.readdirSync(root).filter((f) => f.endsWith(".glb"))) {
    const p = path.join(root, name);
    const stat = fs.statSync(p);

    // A Git LFS pointer is ~130 bytes of text and says nothing about the real
    // asset. Read the size it declares instead of "passing" a pointer.
    let size = stat.size;
    if (stat.size < 1024) {
      const head = fs.readFileSync(p, "utf8");
      const m = head.match(/^size (\d+)$/m);
      if (/git-lfs/.test(head) && m) {
        size = Number(m[1]);
        lfs++;
      }
    }

    checked++;
    total += size;

    if (size <= MAX_BYTES) continue;

    if (isMirror) {
      // Generated by the Editor from the source. Not fixable in the code lane.
      console.warn(
        `WARN  ${p} is ${(size / 1048576).toFixed(2)} MB — the shipped mirror is ` +
        `STALE.\n` +
        `      The source has been optimised; this copy has not been refreshed, so ` +
        `this is\n      what the build still ships. Fix in the Editor:\n` +
        `        Isoperia.EditorTools.IsoperiaOwnedModelPreparation.SyncEncounterActors\n` +
        `      (CopyIfStale now replaces a mirror whose size differs from its source.)`
      );
      stale++;
      continue;
    }

    console.error(
      `FAIL  ${p} is ${(size / 1048576).toFixed(2)} MB ` +
      `(limit ${(MAX_BYTES / 1048576).toFixed(2)} MB)\n` +
      `      Run: node scripts/optimize-glb.cjs ${p} ${p} --keep-anims\n` +
      `      Typical result is 86-94% smaller with no visible change at the ` +
      `size these render.`
    );
    failures++;
  }
}

if (checked === 0) {
  console.log("SKIP  no .glb models found.");
  process.exit(0);
}

if (failures === 0) {
  console.log(
    `PASS  ${checked} model(s) checked, ${(total / 1048576).toFixed(2)} MB total` +
    (lfs ? ` (${lfs} read from LFS pointers)` : "") +
    (stale ? `; ${stale} stale mirror(s) reported above` : "; sources all within budget")
  );
}

console.log(failures === 0 ? "\nmodel budget OK" : `\n${failures} over budget`);
process.exit(failures === 0 ? 0 : 1);

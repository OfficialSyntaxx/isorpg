#!/usr/bin/env node
// Generate src/core/ModelManifest.ts from whatever GLBs are actually in
// public/models.
//
// ACTOR_CLIPS names files a character *would* like to use — including rigged
// clips that haven't been generated yet. Requesting those produces a 404 on every
// boot and, worse, makes "is this asset missing?" invisible among real failures.
// Generating the available set at build time lets spawnActor skip anything that
// isn't shipped, so the manifest can name future files safely and they light up
// the moment they're dropped in.
//
// Run automatically via the `prebuild` / `predev` scripts.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const MODELS = path.join(ROOT, "public", "models");
const CLIPS = path.join(MODELS, "clips");
const OUT = path.join(ROOT, "src", "core", "ModelManifest.ts");

const names = fs.existsSync(MODELS)
  ? fs.readdirSync(MODELS).filter((f) => f.endsWith(".glb")).map((f) => f.replace(/\.glb$/, "")).sort()
  : [];

const clips = fs.existsSync(CLIPS)
  ? fs.readdirSync(CLIPS).filter((f) => f.endsWith(".clip.json")).map((f) => f.replace(/\.clip\.json$/, "")).sort()
  : [];

const body = `// GENERATED by scripts/gen-model-manifest.cjs — do not edit by hand.
// Lists the GLBs present in public/models at build time, so the loader never
// requests a model that isn't shipped.

export const AVAILABLE_MODELS: ReadonlySet<string> = new Set(${JSON.stringify(names)});

export function hasModel(name: string): boolean {
  // An empty manifest means the generator hasn't run; don't block loading then.
  return AVAILABLE_MODELS.size === 0 || AVAILABLE_MODELS.has(name);
}

/** Shared animation clips present in public/models/clips (see ClipLibrary). */
export const AVAILABLE_CLIPS: ReadonlySet<string> = new Set(${JSON.stringify(clips)});

export function hasClip(name: string): boolean {
  return AVAILABLE_CLIPS.size === 0 || AVAILABLE_CLIPS.has(name);
}
`;

const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (prev !== body) {
  fs.writeFileSync(OUT, body);
  console.log(`model manifest: ${names.length} model(s), ${clips.length} clip(s) — ${[...names, ...clips].join(", ") || "none"}`);
} else {
  console.log(`model manifest: unchanged (${names.length} model(s), ${clips.length} clip(s))`);
}
